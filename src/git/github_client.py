"""GitHub client for pull request creation and API interactions."""

import os
import httpx
from typing import Dict, Any, Optional, List
from ..config import GITHUB_TOKEN, GITHUB_REPO

class GitHubClient:
    """Handles GitHub REST API operations with graceful offline/simulated fallback."""

    def __init__(self, token: Optional[str] = None, repo: Optional[str] = None):
        self.token = token or GITHUB_TOKEN
        self.repo = repo or GITHUB_REPO  # Format: "owner/repository"
        self.api_base = "https://api.github.com"

    def is_configured(self) -> bool:
        """Check if both GitHub token and repo target are provided."""
        return bool(self.token and self.repo and "/" in self.repo)

    def create_pull_request(
        self,
        title: str,
        body: str,
        head_branch: str,
        base_branch: str = "main"
    ) -> Dict[str, Any]:
        """Create a Pull Request on GitHub, or return simulated PR link if unconfigured."""
        if not self.is_configured():
            target_repo = self.repo if (self.repo and "/" in self.repo) else "flip-the-switch/multi-agent-team"
            # Simulated PR link for local/demo runs
            simulated_pr_number = 101
            simulated_url = f"https://github.com/{target_repo}/pull/{simulated_pr_number}"
            return {
                "success": True,
                "pr_number": simulated_pr_number,
                "pr_url": simulated_url,
                "mode": "simulated",
                "message": f"Local branch '{head_branch}' committed. Simulated PR URL created for demonstration."
            }

        headers = {
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {self.token}",
            "X-GitHub-Api-Version": "2022-11-28"
        }
        url = f"{self.api_base}/repos/{self.repo}/pulls"
        payload = {
            "title": title,
            "body": body,
            "head": head_branch,
            "base": base_branch
        }

        try:
            with httpx.Client(timeout=15.0) as client:
                resp = client.post(url, headers=headers, json=payload)
                if resp.status_code == 201:
                    data = resp.json()
                    return {
                        "success": True,
                        "pr_number": data.get("number"),
                        "pr_url": data.get("html_url"),
                        "mode": "github_api",
                        "message": "Pull request created successfully via GitHub API"
                    }
                else:
                    return {
                        "success": False,
                        "pr_number": None,
                        "pr_url": None,
                        "mode": "github_api_error",
                        "error": f"GitHub API error {resp.status_code}: {resp.text}"
                    }
        except Exception as ex:
            return {
                "success": False,
                "pr_number": None,
                "pr_url": None,
                "mode": "network_error",
                "error": str(ex)
            }

    @staticmethod
    def generate_pr_body(
        task_id: str,
        request: str,
        root_cause: str,
        modified_files: List[str],
        review_summary: str,
        tests_passed: int,
        iteration_count: int
    ) -> str:
        """Format an engineering PR description detailing multi-agent collaboration."""
        files_list = "\n".join(f"- `{f}`" for f in modified_files) if modified_files else "- None"
        return (
            f"## Multi-Agent Engineering Fix (Task #{task_id})\n\n"
            f"### Problem Description\n"
            f"{request}\n\n"
            f"### Root Cause (Identified by Cursor)\n"
            f"{root_cause}\n\n"
            f"### Changes Implemented\n"
            f"{files_list}\n\n"
            f"### QA & Code Review (Verified by OpenCode)\n"
            f"- **Verdict**: PASS\n"
            f"- **Tests Passed**: {tests_passed}\n"
            f"- **Review Iterations**: {iteration_count}\n"
            f"- **Critique**: {review_summary}\n\n"
            f"### Human Developer Approval\n"
            f"✅ Explicit human developer approval granted in Telegram prior to PR creation.\n\n"
            f"---\n"
            f"*Generated by Switch Multi-Agent Engineering Team (Codex • Cursor • OpenCode)*"
        )

